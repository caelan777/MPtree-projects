/**
 * The alternative app icons MPTree Pro offers, as Android vector drawables.
 *
 *   node Branding/build-alt-icons.mjs        (run from the workspace root)
 *
 * The classic icon stays the PNG set build-assets.mjs makes. These three are
 * vectors instead: one small XML each rather than five densities of PNG, and
 * drawn from the same master mark so they cannot drift from it.
 *
 * Each icon is an adaptive icon (background layer, foreground layer, and a
 * monochrome layer for Android 13's themed icons) plus a plain layer-list for
 * Android 7, which has no adaptive icons. MPTree-App/src/components/LookSheet.tsx
 * draws the same designs as its previews: change one, change the other.
 *
 * Canvas is 108 x 108, the adaptive icon size. Launchers mask it to their own
 * shape and only promise the middle 72 survives, so the mark stays inside it.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const RES = join(HERE, "..", "MPTree-App", "android", "app", "src", "main", "res");
const master = readFileSync(join(HERE, "source", "mptree-mark.svg"), "utf8");
const MARK = master.match(/\sd="([^"]+)"/)[1];

const circle = (cx, cy, r) => `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0z`;

/** The mark, `size` wide, centred on the canvas. */
const mark = (size, color) => {
  const off = +((108 - size) / 2).toFixed(2);
  const s = +(size / 1000).toFixed(5);
  return `    <group android:translateX="${off}" android:translateY="${off}" android:scaleX="${s}" android:scaleY="${s}">
        <path android:fillColor="${color}" android:fillType="evenOdd" android:pathData="${MARK}" />
    </group>`;
};

const rect = color => `    <path android:fillColor="${color}" android:pathData="M0,0h108v108h-108z" />`;
const disc = (r, color) => `    <path android:fillColor="${color}" android:pathData="${circle(54, 54, r)}" />`;
const ring = (r, color, w) =>
  `    <path android:fillColor="#00000000" android:strokeColor="${color}" android:strokeWidth="${w}" android:pathData="${circle(54, 54, r)}" />`;

const vector = body => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
${body}
</vector>
`;

// Grooves: fine rings from just outside the label to the edge of the canvas.
const grooves = [];
for (let r = 20; r <= 60; r += 2.5) grooves.push(ring(r, "#16FFFFFF", 0.5));

const ICONS = {
  // Inverted classic: black mark on white.
  light: {
    bg: [rect("#FFFFFF")],
    fg: [mark(43.2, "#000000")],
  },
  // A record seen from above, the label carrying the mark.
  vinyl: {
    bg: [rect("#0B0B0B"), ...grooves, ring(34, "#24FFFFFF", 0.8)],
    fg: [disc(17, "#FFFFFF"), mark(20, "#000000")],
  },
  // A black seal on white.
  stamp: {
    bg: [rect("#FFFFFF")],
    fg: [disc(29, "#000000"), mark(30, "#FFFFFF")],
  },
};

const written = [];
const put = (dir, name, text) => {
  mkdirSync(join(RES, dir), { recursive: true });
  writeFileSync(join(RES, dir, name), text);
  written.push(`${dir}/${name}`);
};

for (const [name, { bg, fg }] of Object.entries(ICONS)) {
  put("drawable", `ic_alt_${name}_bg.xml`, vector(bg.join("\n")));
  put("drawable", `ic_alt_${name}_fg.xml`, vector(fg.join("\n")));
  // Themed icons tint this one layer, so it is the mark alone, in any colour.
  put("drawable", `ic_alt_${name}_mono.xml`, vector(mark(43.2, "#FFFFFF")));
  put("mipmap-anydpi-v26", `ic_alt_${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_alt_${name}_bg" />
    <foreground android:drawable="@drawable/ic_alt_${name}_fg" />
    <monochrome android:drawable="@drawable/ic_alt_${name}_mono" />
</adaptive-icon>
`);
  // Android 7 has no adaptive icons: the two layers stacked, square.
  put("mipmap", `ic_alt_${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_alt_${name}_bg" />
    <item android:drawable="@drawable/ic_alt_${name}_fg" />
</layer-list>
`);
}

