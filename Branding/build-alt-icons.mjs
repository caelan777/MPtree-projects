/**
 * The alternative app icons MPTree Pro offers: Android vector drawables, the
 * iPhone's icon sets, and the small white mark the playing notification shows.
 *
 *   node Branding/build-alt-icons.mjs        (run from the workspace root)
 *
 * The classic icon stays the PNG set build-assets.mjs makes. These are drawn
 * from the same master mark so they cannot drift from it. Each layer is
 * described once and written twice: as Android vector XML, and as SVG that is
 * rendered to the iPhone's 1024 px PNGs.
 *
 * Android: each icon is an adaptive icon (background layer, foreground layer,
 * and a monochrome layer for Android 13's themed icons) plus a plain
 * layer-list for Android 7, which has no adaptive icons.
 * iPhone: an "AppIcon-<name>" set in Assets.xcassets, switched to with
 * setAlternateIconName (ios/App/App/SystemPlugin.swift).
 * MPTree-App/src/components/LookSheet.tsx draws the same designs as its
 * previews: change one, change the other.
 *
 * Canvas is 108 x 108, the adaptive icon size. Launchers mask it to their own
 * shape and only promise the middle 72 survives, so the mark stays inside it;
 * the iPhone's square is that middle 72, which makes the mark as big as on
 * the classic icon.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const HERE = dirname(fileURLToPath(import.meta.url));
const RES = join(HERE, "..", "MPTree-App", "android", "app", "src", "main", "res");
const XCASSETS = join(HERE, "..", "MPTree-App", "ios", "App", "App", "Assets.xcassets");
const require = createRequire(join(HERE, "..", "MPTree-App", "node_modules", "x.js"));
const sharp = require("sharp");
const master = readFileSync(join(HERE, "source", "mptree-mark.svg"), "utf8");
const MARK = master.match(/\sd="([^"]+)"/)[1];

const circle = (cx, cy, r) => `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0z`;

/** Android's #AARRGGBB (or #RRGGBB) as SVG paint. */
const paint = (c, attr = "fill") => {
  const h = c.slice(1);
  if (h.length !== 8) return `${attr}="${c}"`;
  return `${attr}="#${h.slice(2)}" ${attr}-opacity="${(parseInt(h.slice(0, 2), 16) / 255).toFixed(3)}"`;
};

/** The mark, `size` wide, centred on the canvas. */
const mark = (size, color) => {
  const off = +((108 - size) / 2).toFixed(2);
  const s = +(size / 1000).toFixed(5);
  return {
    xml: `    <group android:translateX="${off}" android:translateY="${off}" android:scaleX="${s}" android:scaleY="${s}">
        <path android:fillColor="${color}" android:fillType="evenOdd" android:pathData="${MARK}" />
    </group>`,
    svg: `<g transform="translate(${off} ${off}) scale(${s})"><path ${paint(color)} fill-rule="evenodd" d="${MARK}"/></g>`,
  };
};

const rect = color => ({
  xml: `    <path android:fillColor="${color}" android:pathData="M0,0h108v108h-108z" />`,
  svg: `<path ${paint(color)} d="M0,0h108v108h-108z"/>`,
});
const disc = (r, color) => ({
  xml: `    <path android:fillColor="${color}" android:pathData="${circle(54, 54, r)}" />`,
  svg: `<path ${paint(color)} d="${circle(54, 54, r)}"/>`,
});
const ring = (r, color, w) => ({
  xml: `    <path android:fillColor="#00000000" android:strokeColor="${color}" android:strokeWidth="${w}" android:pathData="${circle(54, 54, r)}" />`,
  svg: `<path fill="none" ${paint(color, "stroke")} stroke-width="${w}" d="${circle(54, 54, r)}"/>`,
});

const vector = body => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
${body}
</vector>
`;

// A flower as in MPTree-App/src/flowers.ts (flower()): petals round a heart.
const r1 = v => Math.round(v * 10) / 10;
const petalPath = (len, wide) => {
  const w = r1(len * wide);
  return `M0,0C${w},${r1(-len * 0.3)} ${w},${r1(-len * 0.9)} 0,${r1(-len)}C${-w},${r1(-len * 0.9)} ${-w},${r1(-len * 0.3)} 0,0Z`;
};
const flower = (x, y, r, n, fill, heart) => {
  const d = petalPath(r, n > 8 ? 0.2 : n > 5 ? 0.42 : 0.58);
  const turns = Array.from({ length: n }, (_, i) => r1(i * 360 / n));
  return {
    xml: `    <group android:translateX="${x}" android:translateY="${y}">
${turns.map(a => `        <group android:rotation="${a}"><path android:fillColor="${fill}" android:pathData="${d}" /></group>`).join("\n")}
        <path android:fillColor="${heart}" android:pathData="${circle(0, 0, r1(r * 0.2))}" />
    </group>`,
    svg: `<g transform="translate(${x} ${y})">${turns.map(a => `<g transform="rotate(${a})"><path ${paint(fill)} d="${d}"/></g>`).join("")}<path ${paint(heart)} d="${circle(0, 0, r1(r * 0.2))}"/></g>`,
  };
};

// Grooves: fine rings from just outside the label to the edge of the canvas.
const grooves = [];
for (let r = 20; r <= 60; r += 2.5) grooves.push(ring(r, "#16FFFFFF", 0.5));

const ICONS = {
  // Inverted classic: black mark on white.
  light: {
    bg: [rect("#FFFFFF")],
    fg: [mark(43.2, "#000000")],
  },
  // A record seen from above, the label carrying the mark.
  vinyl: {
    bg: [rect("#0B0B0B"), ...grooves, ring(34, "#24FFFFFF", 0.8)],
    fg: [disc(17, "#FFFFFF"), mark(20, "#000000")],
  },
  // A black seal on white.
  stamp: {
    bg: [rect("#FFFFFF")],
    fg: [disc(29, "#000000"), mark(30, "#FFFFFF")],
  },
  // Aviela: the mark in ink on petal pink, a rose flower on its shoulder, as
  // the app wears it in Aviela's "One flower".
  aviela: {
    bg: [rect("#FFD5E6")],
    fg: [mark(43.2, "#20181B"), flower(74, 33, 13, 6, "#EE8FB4", "#F3C14B")],
  },
  // Lantern: the mark in its green light, glowing out of black.
  lantern: {
    bg: [rect("#050906"), disc(40, "#1035E08A"), disc(31, "#1A35E08A"), disc(23, "#2435E08A")],
    fg: [mark(43.2, "#35E08A")],
  },
};

const written = [];
const put = (dir, name, text) => {
  mkdirSync(join(RES, dir), { recursive: true });
  writeFileSync(join(RES, dir, name), text);
  written.push(`${dir}/${name}`);
};

for (const [name, { bg, fg }] of Object.entries(ICONS)) {
  put("drawable", `ic_alt_${name}_bg.xml`, vector(bg.map(l => l.xml).join("\n")));
  put("drawable", `ic_alt_${name}_fg.xml`, vector(fg.map(l => l.xml).join("\n")));
  // Themed icons tint this one layer, so it is the mark alone, in any colour.
  put("drawable", `ic_alt_${name}_mono.xml`, vector(mark(43.2, "#FFFFFF").xml));
  put("mipmap-anydpi-v26", `ic_alt_${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_alt_${name}_bg" />
    <foreground android:drawable="@drawable/ic_alt_${name}_fg" />
    <monochrome android:drawable="@drawable/ic_alt_${name}_mono" />
</adaptive-icon>
`);
  // Android 7 has no adaptive icons: the two layers stacked, square.
  put("mipmap", `ic_alt_${name}.xml`, `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/ic_alt_${name}_bg" />
    <item android:drawable="@drawable/ic_alt_${name}_fg" />
</layer-list>
`);

  // The iPhone: the middle 72 of the canvas, 1024 px square, no transparency
  // (iOS refuses an app icon with an alpha channel).
  const set = join(XCASSETS, `AppIcon-${name}.appiconset`);
  mkdirSync(set, { recursive: true });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="18 18 72 72">${[...bg, ...fg].map(l => l.svg).join("")}</svg>`;
  await sharp(Buffer.from(svg), { density: 1024 / 72 * 72 }).resize(1024, 1024).flatten({ background: "#000000" }).png().toFile(join(set, `AppIcon-${name}.png`));
  writeFileSync(join(set, "Contents.json"), JSON.stringify({
    images: [{ filename: `AppIcon-${name}.png`, idiom: "universal", platform: "ios", size: "1024x1024" }],
    info: { author: "xcode", version: 1 },
  }, null, 2) + "\n");
  written.push(`ios AppIcon-${name}.appiconset`);
}

// The small icon of the playing notification: on the lock screen and in the
// status bar Android draws only its shape, in white, so it must be the mark
// alone on nothing. The launcher icon there came out as a plain dot.
{
  const off = 1.5, k = (24 - 2 * off) / 1000;
  put("drawable", "ic_stat_mptree.xml", `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by Branding/build-alt-icons.mjs. Do not hand-edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
    <group android:translateX="${off}" android:translateY="${off}" android:scaleX="${k}" android:scaleY="${k}">
        <path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="${MARK}" />
    </group>
</vector>
`);
}

